#!/usr/bin/env bash
# Seals the link to Global's shared Airtable view (M1, ADR-0005) for the cluster into a gitops checkout (settings:
# scripts/lib/deploy-settings.sh).
# The link is a credential: anyone holding it reads every Spain signup. It is read with hidden input, never printed,
# logged or written unencrypted, and reaches kubectl through /dev/fd. When Global changes the link, delete the sealed
# file and run this again: no code changes.
#
# Usage: scripts/seal-airtable-link.sh <path-to-gitops>
# Refuses to overwrite.
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
. "$(dirname "$0")/lib/deploy-settings.sh"
load_deploy_settings "$GITOPS" APP_DIR KUBESEAL_ARGS
NAMESPACE="${NAMESPACE:-pauseai-es-backoffice}"
read -r -a KUBESEAL_ARGS <<<"$KUBESEAL_ARGS"

DIR="$GITOPS/$APP_DIR/secrets"
OUT="$DIR/backoffice-airtable.yaml"
[ -d "$DIR" ] || { echo "Not a gitops checkout with the backoffice's secrets: $DIR is missing" >&2; exit 1; }
[ ! -e "$OUT" ] || { echo "Refusing to overwrite $OUT" >&2; exit 1; }

printf 'Shared view link (input hidden): '
IFS= read -rs AIRTABLE_LINK
echo
# A shared view's link: https://airtable.com/app…/shr… (a base id, then a share id), nothing else.
if [[ ! "$AIRTABLE_LINK" =~ ^https://airtable\.com/app[A-Za-z0-9]{14}/shr[A-Za-z0-9]{14}(/[A-Za-z0-9/]*)?$ ]]; then
  unset AIRTABLE_LINK
  echo "That isn't a shared view link (https://airtable.com/app…/shr…); nothing sealed" >&2
  exit 1
fi

tmp="$OUT.tmp"
if ! {
  printf '# yamllint disable rule:line-length\n'
  printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
  printf "# AIRTABLE_SHARED_VIEW_URL: Global's shared view of Spain's signups (a credential, ADR-0005).\n"
  printf '# Generated by scripts/seal-airtable-link.sh in pauseai-en-espanol/backoffice.\n'
  kubectl create secret generic backoffice-airtable -n "$NAMESPACE" \
    --from-file=AIRTABLE_SHARED_VIEW_URL=<(printf %s "$AIRTABLE_LINK") --dry-run=client -o yaml \
    | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
    | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
} >"$tmp"; then
  rm -f "$tmp"
  unset AIRTABLE_LINK
  echo "Failed to seal $OUT" >&2
  exit 1
fi
mv "$tmp" "$OUT"
unset AIRTABLE_LINK
echo "sealed $OUT"
echo "Done. Turn backoffice-api.airtableSync on in the gitops values (docs/runbooks/deploying.md), then commit both."
