#!/usr/bin/env bash
# Sets up the Telegram bot (M1, ADR-0004) in one run, for the danilupion.com cluster (as aisafety-newsroom's script):
#   1. checks the bot token with Telegram (getMe) before anything is sealed, and says which bot it belongs to;
#   2. seals the token and a new webhook secret into a gitops checkout;
#   3. prints the values to put under backoffice-api.telegram in the gitops values.
# The command menu needs nothing here either: the API sets it on every start, in English and, for Spanish Telegram,
# in Spanish (PLAN R38), from packages/i18n.
# Nothing secret is printed or written unencrypted: the token lives in a shell variable, reaches curl through stdin and
# kubectl through /dev/fd, never argv or a file. Who may use the bot isn't configured here: only Telegram accounts
# linked to a staff member from the web app (with the second factor) are listened to.
#
# Usage: scripts/seal-telegram-secret.sh <path-to-gitops>
# Run it in a terminal: it asks for the token (input hidden). Refuses to overwrite: to rotate, delete the sealed file
# first. The API registers the webhook on its next start.
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
# Overridable for a dry run against a throwaway certificate and a stand-in Bot API.
read -r -a KUBESEAL_ARGS <<<"${KUBESEAL_ARGS:---context danilupion.com --controller-namespace sealed-secrets --controller-name sealed-secrets}"
TELEGRAM_API="${TELEGRAM_API:-https://api.telegram.org}"

DIR="$GITOPS/clusters/danilupion-com/resources/apps/backoffice/secrets"
OUT="$DIR/backoffice-telegram.yaml"
[ -d "$DIR" ] || { echo "Not a gitops checkout with the backoffice's secrets: $DIR is missing" >&2; exit 1; }
[ ! -e "$OUT" ] || { echo "Refusing to overwrite $OUT" >&2; exit 1; }

# bot_api <method> <json body>: the Bot API's answer. The URL, which holds the token, goes to curl as a config line on
# stdin, never as an argument.
bot_api() {
  printf 'url = "%s/bot%s/%s"\n' "$TELEGRAM_API" "$BOT_TOKEN" "$1" |
    curl -sS --max-time 15 -K - -H 'content-type: application/json' -d "$2"
}

printf 'Bot token from BotFather: '
IFS= read -rs BOT_TOKEN
echo
# BotFather's tokens look like 123456789:AA…; checked so a stray paste doesn't go anywhere.
[[ "$BOT_TOKEN" =~ ^[0-9]+:[A-Za-z0-9_-]{30,}$ ]] || { echo "That doesn't look like a bot token" >&2; exit 1; }

username="$(bot_api getMe '{}' | jq -r 'if .ok then .result.username else empty end' 2>/dev/null || true)"
[ -n "$username" ] || { echo "Telegram doesn't accept that token: check it in BotFather" >&2; exit 1; }
echo "Telegram knows this token as @$username"

# 64 hex characters: within what Telegram takes as a secret_token (1 to 256 of A-Z, a-z, 0-9, '_', '-').
WEBHOOK_SECRET="$(openssl rand -hex 32)"

tmp="$OUT.tmp"
if ! {
  printf '# yamllint disable rule:line-length\n'
  printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
  printf '# TELEGRAM_BOT_TOKEN (BotFather, @%s) and TELEGRAM_WEBHOOK_SECRET (openssl rand -hex 32) for the API.\n' "$username"
  printf '# Generated by scripts/seal-telegram-secret.sh in pauseai-en-espanol/backoffice.\n'
  kubectl create secret generic backoffice-telegram -n backoffice \
    --from-file=TELEGRAM_BOT_TOKEN=<(printf %s "$BOT_TOKEN") \
    --from-file=TELEGRAM_WEBHOOK_SECRET=<(printf %s "$WEBHOOK_SECRET") --dry-run=client -o yaml \
    | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
    | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
} >"$tmp"; then
  rm -f "$tmp"
  echo "Failed to seal $OUT" >&2
  exit 1
fi
mv "$tmp" "$OUT"
unset BOT_TOKEN WEBHOOK_SECRET
echo "sealed $OUT"
cat <<EOF
Done. In clusters/danilupion-com/values/apps/backoffice.yaml, under backoffice-api:, set

  telegram:
    enabled: true
    secret:
      name: backoffice-telegram
    botUsername: $username

and under backoffice-web.route: telegramWebhook: true. Review with git -C "$GITOPS" diff, then commit.
EOF
