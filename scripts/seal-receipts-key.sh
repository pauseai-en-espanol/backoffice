#!/usr/bin/env bash
# Generates the key that encrypts every receipt on the API's volume (RECEIPTS_KEY, M6, ADR-0006 decision 7) and seals
# it for the cluster into a gitops checkout (settings: scripts/lib/deploy-settings.sh): one SealedSecret,
# backoffice-receipts-key with the key `RECEIPTS_KEY`, which the API chart's receipts.keySecret names. Nothing secret is
# printed or written unencrypted: the key lives in a shell variable and reaches kubectl through /dev/fd, never argv or a
# file.
#
# Usage: scripts/seal-receipts-key.sh <path-to-gitops>
# Non-interactive. Refuses to overwrite, and there is no rotating it: a new key opens none of the receipts stored with
# the old one, so losing the key loses every receipt. Keep it as the backup plan says (docs/runbooks/receipts.md).
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
. "$(dirname "$0")/lib/deploy-settings.sh"
load_deploy_settings "$GITOPS" APP_DIR KUBESEAL_ARGS
NAMESPACE="${NAMESPACE:-pauseai-es-backoffice}"
read -r -a KUBESEAL_ARGS <<<"$KUBESEAL_ARGS"

DIR="$GITOPS/$APP_DIR/secrets"
OUT="$DIR/backoffice-receipts-key.yaml"
[ -d "$DIR" ] || { echo "Not a gitops checkout with the backoffice's secrets: $DIR is missing" >&2; exit 1; }
[ ! -e "$OUT" ] || { echo "Refusing to overwrite $OUT: a new key opens none of the stored receipts" >&2; exit 1; }

# 32 random bytes in base64, as the API reads it (apps/api/src/accounting/receipt-store.ts).
KEY="$(openssl rand -base64 32)"
[[ "$KEY" =~ ^[A-Za-z0-9+/]{43}=$ ]] || { echo "Couldn't generate the key" >&2; exit 1; }

tmp="$OUT.tmp"
if ! {
  printf '# yamllint disable rule:line-length\n'
  printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
  printf "# RECEIPTS_KEY: encrypts every receipt on the API's volume (openssl rand, 32 bytes; ADR-0006).\n"
  printf '# Generated by scripts/seal-receipts-key.sh in pauseai-en-espanol/backoffice.\n'
  kubectl create secret generic backoffice-receipts-key -n "$NAMESPACE" \
    --from-file=RECEIPTS_KEY=<(printf %s "$KEY") --dry-run=client -o yaml \
    | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
    | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
} >"$tmp"; then
  rm -f "$tmp"
  unset KEY
  echo "Failed to seal $OUT" >&2
  exit 1
fi
mv "$tmp" "$OUT"
unset KEY
echo "sealed $OUT"
values_file="${VALUES_FILE:-the backoffice values file}"
cat <<EOF
Done. In $values_file, under backoffice-api:, turn receipts on with its size, storage class and
keySecret: { name: backoffice-receipts-key } (docs/runbooks/receipts.md). Review with git -C "$GITOPS" diff, then
commit. Once deployed, keep a copy of the key where the backup plan says: without it, no receipt opens.
EOF
