#!/usr/bin/env bash
# Generates the backoffice's database passwords and Better Auth's secret, and seals them for the cluster into a gitops
# checkout (ADR-0001, docs/runbooks/deploying.md), with the settings in its backoffice-deploy.env
# (scripts/lib/deploy-settings.sh). Nothing secret is printed or written unencrypted: passwords live in shell variables
# and reach kubectl through /dev/fd (process substitution), never through argv or a file.
#
# Usage: scripts/seal-gitops-secrets.sh <path-to-gitops>
# Non-interactive. Refuses to overwrite: to rotate, delete the files first. The five passwords are always generated
# together: the postgresql provisioning hook sets them on the roles, and each connection string carries the same one.
# The Harbor pull secret, the GlitchTip DSNs, mail, the bot and the Airtable link have scripts of their own
# (seal-harbor-pull-secret.sh, seal-glitchtip-dsns.sh, seal-mail-secret.sh, seal-telegram-secret.sh,
# seal-airtable-link.sh), since each needs something only a person has.
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
. "$(dirname "$0")/lib/deploy-settings.sh"
load_deploy_settings "$GITOPS" APP_DIR PG_DIR PG_NAMESPACE DB_HOST KUBESEAL_ARGS
NAMESPACE="${NAMESPACE:-pauseai-es-backoffice}"
read -r -a KUBESEAL_ARGS <<<"$KUBESEAL_ARGS"

PG_DIR="$GITOPS/$PG_DIR"
APP_DIR="$GITOPS/$APP_DIR/secrets"
DB_NAME="pauseai_backoffice"
ROLES=(owner app auth ingest public)

files=("$PG_DIR/backoffice-db-credentials.yaml" "$APP_DIR/backoffice-better-auth.yaml")
for role in "${ROLES[@]}"; do
  files+=("$APP_DIR/backoffice-$role-db.yaml")
done
for f in "${files[@]}"; do
  if [ -e "$f" ]; then
    echo "Refusing to overwrite $f" >&2
    exit 1
  fi
done
[ -d "$PG_DIR" ] || { echo "Not a gitops checkout: $PG_DIR is missing" >&2; exit 1; }
mkdir -p "$APP_DIR"

# seal <out> <header> <wave|-> <kubectl create secret args...>
# Writes header comments plus the SealedSecret. Secrets in the app namespace get sync wave -2, so Argo CD creates them
# before the migration Job (wave -1) and the Deployments (wave 0).
seal() {
  local out="$1" header="$2" wave="$3"
  shift 3
  local tmp="$out.tmp"
  if ! {
    printf '# yamllint disable rule:line-length\n'
    printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
    printf '%s\n' "$header"
    kubectl create secret "$@" --dry-run=client -o yaml \
      | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
      | if [ "$wave" = - ]; then sed '/^---$/d'; else
          kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=$wave" -o yaml
        fi
  } >"$tmp"; then
    rm -f "$tmp"
    echo "Failed to seal $out" >&2
    exit 1
  fi
  mv "$tmp" "$out"
  echo "sealed $out"
}

# One variable per role (pw_owner, pw_app, …): macOS's bash 3.2 has no associative arrays.
for role in "${ROLES[@]}"; do
  printf -v "pw_$role" '%s' "$(openssl rand -hex 32)"
done
password() { local name="pw_$1"; printf %s "${!name}"; }
auth_secret="$(openssl rand -hex 32)"
url() { printf 'postgres://pauseai_backoffice_%s:%s@%s/%s?sslmode=disable' "$1" "$2" "$DB_HOST" "$DB_NAME"; }

seal "$PG_DIR/backoffice-db-credentials.yaml" \
  "# Read by the postgresql provisioning hook: owner and extra-role passwords for the pauseai_backoffice database
# (openssl rand -hex 32 each). Each must match DATABASE_URL in $NAMESPACE/backoffice-<role>-db.
# Generated by scripts/seal-gitops-secrets.sh in pauseai-en-espanol/backoffice." - \
  generic backoffice-db-credentials -n "$PG_NAMESPACE" \
  --from-file=BACKOFFICE_OWNER_PASSWORD=<(password owner) \
  --from-file=BACKOFFICE_APP_PASSWORD=<(password app) \
  --from-file=BACKOFFICE_AUTH_PASSWORD=<(password auth) \
  --from-file=BACKOFFICE_INGEST_PASSWORD=<(password ingest) \
  --from-file=BACKOFFICE_PUBLIC_PASSWORD=<(password public)

describe() {
  case "$1" in
    owner) echo 'the migration Job only' ;;
    app) echo 'the API: staff and bot routes, always through withActor' ;;
    auth) echo "Better Auth, in the API, and the session-cleanup job" ;;
    ingest) echo 'the Airtable sync (M1)' ;;
    public) echo "the census form's routes (M2)" ;;
  esac
}
for role in "${ROLES[@]}"; do
  upper="$(printf %s "$role" | tr '[:lower:]' '[:upper:]')"
  seal "$APP_DIR/backoffice-$role-db.yaml" \
    "# DATABASE_URL for pauseai_backoffice_$role ($(describe "$role")): $(url "$role" "<${upper}_PASSWORD>")" -2 \
    generic "backoffice-$role-db" -n "$NAMESPACE" --from-file=DATABASE_URL=<(url "$role" "$(password "$role")")
done

seal "$APP_DIR/backoffice-better-auth.yaml" \
  "# BETTER_AUTH_SECRET: the key Better Auth signs sessions with and encrypts TOTP secrets with (openssl rand -hex 32).
# Set once: changing it signs everyone out and makes every enrolled authenticator unreadable." -2 \
  generic backoffice-better-auth -n "$NAMESPACE" --from-file=BETTER_AUTH_SECRET=<(printf %s "$auth_secret")

unset pw_owner pw_app pw_auth pw_ingest pw_public auth_secret
echo "Done. Review with: git -C \"$GITOPS\" status"
