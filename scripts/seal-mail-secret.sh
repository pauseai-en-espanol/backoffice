#!/usr/bin/env bash
# Seals the API's SMTP_URL (Mailu's submission, ADR-0001, mail) for the danilupion.com cluster into a gitops checkout.
# The URL goes to Mailu's front inside the cluster, over SMTPS (465), checking the certificate against the mail host's
# name. Nothing secret is printed or written unencrypted: the password is read with hidden input, URL-encoded in a
# Python child that reads it from stdin, and reaches kubectl through /dev/fd.
#
# Usage: scripts/seal-mail-secret.sh <path-to-gitops>
# Asks for the sending account (e.g. avisos@pauseai.es, made first in Mailu's admin) and its password. Refuses to
# overwrite: to rotate, delete the file first. Set MAIL_FROM in the gitops values to the same address.
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
read -r -a KUBESEAL_ARGS <<<"${KUBESEAL_ARGS:---context danilupion.com --controller-namespace sealed-secrets --controller-name sealed-secrets}"
SMTP_HOST="${SMTP_HOST:-mailu-front.mailu.svc.cluster.local}"
SMTP_PORT="${SMTP_PORT:-465}"
# The name on Mailu's certificate, which the in-cluster host doesn't carry.
TLS_SERVERNAME="${TLS_SERVERNAME:-mail.pauseai.es}"

DIR="$GITOPS/clusters/danilupion-com/resources/apps/pauseai-es-backoffice/secrets"
OUT="$DIR/backoffice-mail.yaml"
[ -d "$DIR" ] || { echo "Not a gitops checkout with the backoffice's secrets: $DIR is missing" >&2; exit 1; }
[ ! -e "$OUT" ] || { echo "Refusing to overwrite $OUT" >&2; exit 1; }

printf 'Sending account (e.g. avisos@pauseai.es): '
IFS= read -r account
[[ "$account" =~ ^[^@[:space:]]+@[^@[:space:]]+\.[a-z]+$ ]] || { echo "That isn't an address" >&2; exit 1; }
printf 'Its password: '
IFS= read -rs MAIL_PASSWORD
echo
[ -n "$MAIL_PASSWORD" ] || { echo "Empty password" >&2; exit 1; }

smtp_url() {
  printf '%s\n%s\n' "$account" "$MAIL_PASSWORD" | python3 -c '
import sys, urllib.parse
user, password = sys.stdin.read().split("\n")[:2]
q = lambda s: urllib.parse.quote(s, safe="")
host, port, name = sys.argv[1:4]
print(f"smtps://{q(user)}:{q(password)}@{host}:{port}?tls.servername={name}", end="")' \
    "$SMTP_HOST" "$SMTP_PORT" "$TLS_SERVERNAME"
}

tmp="$OUT.tmp"
if ! {
  printf '# yamllint disable rule:line-length\n'
  printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
  printf '# SMTP_URL for the API: smtps://%s:<password>@%s:%s?tls.servername=%s\n' \
    "$account" "$SMTP_HOST" "$SMTP_PORT" "$TLS_SERVERNAME"
  printf '# Generated by scripts/seal-mail-secret.sh in pauseai-en-espanol/backoffice.\n'
  kubectl create secret generic backoffice-mail -n pauseai-es-backoffice \
    --from-file=SMTP_URL=<(smtp_url) --dry-run=client -o yaml \
    | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
    | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
} >"$tmp"; then
  rm -f "$tmp"
  echo "Failed to seal $OUT" >&2
  exit 1
fi
mv "$tmp" "$OUT"
unset MAIL_PASSWORD
echo "sealed $OUT"
echo "Done. Set backoffice-api.mail.from to $account in the gitops values, then commit both."
