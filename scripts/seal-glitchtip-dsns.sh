#!/usr/bin/env bash
# Seals the GlitchTip DSN of each backoffice app (api, web, forms) for the cluster into a gitops checkout (ADR-0003,
# observability; settings: scripts/lib/deploy-settings.sh). Nothing secret is printed or written unencrypted: each DSN
# is read with hidden input and reaches kubectl through /dev/fd (process substitution), never through argv or a file.
#
# Usage: scripts/seal-glitchtip-dsns.sh <path-to-gitops> [app...]
# The apps default to api, web and forms; name some to seal only theirs (forms, say, once the others are sealed).
# Paste each project's DSN from GlitchTip (project settings, Client Keys). The host is rewritten to GLITCHTIP_HOST,
# GlitchTip as the pods reach it inside the cluster, which the host its UI shows needn't be. Refuses to overwrite: to
# rotate, delete the files first.
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
. "$(dirname "$0")/lib/deploy-settings.sh"
load_deploy_settings "$GITOPS" APP_DIR GLITCHTIP_HOST KUBESEAL_ARGS
NAMESPACE="${NAMESPACE:-pauseai-es-backoffice}"
read -r -a KUBESEAL_ARGS <<<"$KUBESEAL_ARGS"

APP_DIR="$GITOPS/$APP_DIR/secrets"
APPS=("${@:2}")
[ "${#APPS[@]}" -gt 0 ] || APPS=(api web forms)

[ -d "$APP_DIR" ] || { echo "Not a gitops checkout with the backoffice's secrets: $APP_DIR is missing" >&2; exit 1; }
for app in "${APPS[@]}"; do
  if [ -e "$APP_DIR/backoffice-$app-glitchtip.yaml" ]; then
    echo "Refusing to overwrite $APP_DIR/backoffice-$app-glitchtip.yaml" >&2
    exit 1
  fi
done

for app in "${APPS[@]}"; do
  printf 'GlitchTip DSN of project backoffice-%s: ' "$app"
  IFS= read -rs dsn
  echo
  # https://<key>@<any host>/<project> becomes http://<key>@<GLITCHTIP_HOST>/<project>.
  if [[ ! "$dsn" =~ ^https?://([0-9A-Fa-f-]+)@[^/@]+/([0-9]+)/?$ ]]; then
    echo "That is not a GlitchTip DSN (expected https://<key>@<host>/<project>); nothing written for $app" >&2
    exit 1
  fi
  internal="http://${BASH_REMATCH[1]}@$GLITCHTIP_HOST/${BASH_REMATCH[2]}"
  out="$APP_DIR/backoffice-$app-glitchtip.yaml"
  tmp="$out.tmp"
  # Sync wave -2, like the other backoffice secrets: created before the Deployments (wave 0).
  if ! {
    printf '# yamllint disable rule:line-length\n'
    printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
    printf '# SENTRY_DSN of GlitchTip project backoffice-%s, as the pods reach GlitchTip.\n' "$app"
    printf '# Generated by scripts/seal-glitchtip-dsns.sh in pauseai-en-espanol/backoffice.\n'
    kubectl create secret generic "backoffice-$app-glitchtip" -n "$NAMESPACE" \
      --from-file=SENTRY_DSN=<(printf %s "$internal") --dry-run=client -o yaml \
      | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
      | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
  } >"$tmp"; then
    rm -f "$tmp"
    echo "Failed to seal $out" >&2
    exit 1
  fi
  mv "$tmp" "$out"
  echo "sealed $out"
done
unset dsn internal
echo "Done. Review with: git -C \"$GITOPS\" status"
