#!/usr/bin/env bash
# Seals the Harbor pull secret the cluster pulls the backoffice's images with: the pauseai-es project's robot, which
# PauseAI España's other apps pull with too, sealed once more for the backoffice's namespace (a sealed secret opens
# only in the namespace it was sealed for). Settings: scripts/lib/deploy-settings.sh. Before sealing, it asks Harbor
# for a pull token as the cluster will, so a wrong secret, or a robot without pull rights, is caught here rather than
# as a 401 in the cluster. Nothing secret is printed or written unencrypted: the secret reaches curl through stdin and
# kubectl through /dev/fd, never argv.
#
# Usage: scripts/seal-harbor-pull-secret.sh <path-to-gitops>
# Run it in a terminal, from a machine that reaches the registry: it asks for the robot's secret (input hidden).
# Replaces any existing pull secret. CHECK_ONLY=1 checks the secret and seals nothing.
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
. "$(dirname "$0")/lib/deploy-settings.sh"
load_deploy_settings "$GITOPS" APP_DIR HARBOR_URL HARBOR_ROBOT KUBESEAL_ARGS
NAMESPACE="${NAMESPACE:-pauseai-es-backoffice}"
read -r -a KUBESEAL_ARGS <<<"$KUBESEAL_ARGS"
HARBOR_REPOSITORY="${HARBOR_REPOSITORY:-pauseai-es/backoffice-migrations}"
# The registry's host, as the cluster's container runtime looks it up in the pull secret.
REGISTRY_HOST="${HARBOR_URL#*://}"
REGISTRY_HOST="${REGISTRY_HOST%%/*}"

DIR="$GITOPS/$APP_DIR/secrets"
OUT="$DIR/pauseai-es-harbor-pull.yaml"
[ -d "$DIR" ] || { echo "Not a gitops checkout with the backoffice: $DIR is missing" >&2; exit 1; }

printf 'Harbor secret for %s: ' "$HARBOR_ROBOT"
IFS= read -rs HARBOR_SECRET
echo
[ -n "$HARBOR_SECRET" ] || { echo "Empty Harbor secret" >&2; exit 1; }

# Harbor's token service answers a wrong secret with 401, and a robot without pull rights with a token that grants
# nothing: the registry then answers 401 too, which is all the cluster shows. Telling the two apart here.
answer="$(printf 'user = "%s:%s"\n' "$HARBOR_ROBOT" "$HARBOR_SECRET" |
  curl -sS --max-time 15 -K - -w '\n%{http_code}' \
    "$HARBOR_URL/service/token?service=harbor-registry&scope=repository:$HARBOR_REPOSITORY:pull" || true)"
status="${answer##*$'\n'}"
case "$status" in
  200)
    granted="$(printf '%s' "${answer%$'\n'*}" | python3 -c '
import base64, json, sys
token = json.load(sys.stdin)["token"]
payload = token.split(".")[1]
claims = json.loads(base64.urlsafe_b64decode(payload + "=" * (-len(payload) % 4)))
print(",".join(a for entry in claims.get("access") or [] for a in entry.get("actions", [])))' 2>/dev/null || true)"
    if [[ ",$granted," != *",pull,"* ]]; then
      echo "Harbor accepts the secret, but the robot can't pull $HARBOR_REPOSITORY: give it Repository: Pull on" >&2
      echo "the project, then run this again" >&2
      exit 1
    fi
    echo "Harbor accepts the secret, and the robot can pull $HARBOR_REPOSITORY"
    ;;
  401)
    echo "Harbor refuses this robot and secret: refresh the robot's secret in Harbor and paste the new one" >&2
    exit 1
    ;;
  *)
    echo "Couldn't check with Harbor (answer: ${status:-none}); does this machine reach $HARBOR_URL?" >&2
    exit 1
    ;;
esac
if [ -n "${CHECK_ONLY:-}" ]; then
  echo "CHECK_ONLY: nothing sealed"
  exit 0
fi

tmp="$OUT.tmp"
if ! {
  printf '# yamllint disable rule:line-length\n'
  printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
  printf '# Pull secret for the pauseai-es registry project (%s, pull only), on the default SA.\n' "$HARBOR_ROBOT"
  printf '# Generated by scripts/seal-harbor-pull-secret.sh in pauseai-en-espanol/backoffice.\n'
  kubectl create secret generic pauseai-es-harbor-pull -n "$NAMESPACE" \
    --type=kubernetes.io/dockerconfigjson \
    --from-file=.dockerconfigjson=<(REGISTRY_HOST="$REGISTRY_HOST" HARBOR_ROBOT="$HARBOR_ROBOT" \
      HARBOR_SECRET="$HARBOR_SECRET" jq -cn '
      {auths: {(env.REGISTRY_HOST): {username: env.HARBOR_ROBOT, password: env.HARBOR_SECRET,
        auth: ("\(env.HARBOR_ROBOT):\(env.HARBOR_SECRET)" | @base64)}}}') \
    --dry-run=client -o yaml \
    | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
    | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
} >"$tmp"; then
  rm -f "$tmp"
  echo "Failed to seal $OUT" >&2
  exit 1
fi
mv "$tmp" "$OUT"
unset HARBOR_SECRET
echo "sealed $OUT"
echo "Done. Commit it in gitops; Argo CD retries the sync on its own once it changes."
