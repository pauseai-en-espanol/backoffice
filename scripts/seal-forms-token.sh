#!/usr/bin/env bash
# Generates the secret the census form's server and the API share (FORMS_TOKEN, M2, ADR-0002 §7) and seals it for the
# danilupion.com cluster into a gitops checkout: one SealedSecret, backoffice-forms-token with the key `token`, which
# the API chart's formsTokenSecret and the forms chart's formsTokenSecret both name. Nothing secret is printed or
# written unencrypted: the token lives in a shell variable and reaches kubectl through /dev/fd, never argv or a file.
#
# Usage: scripts/seal-forms-token.sh <path-to-gitops>
# Non-interactive. Refuses to overwrite: to rotate, delete the sealed file first, run this again, and restart the API
# and the form together (each refuses the other's calls until both have the new one).
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
# Overridable for a dry run against a throwaway certificate (KUBESEAL_ARGS="--cert cert.pem").
read -r -a KUBESEAL_ARGS <<<"${KUBESEAL_ARGS:---context danilupion.com --controller-namespace sealed-secrets --controller-name sealed-secrets}"

DIR="$GITOPS/clusters/danilupion-com/resources/apps/backoffice/secrets"
OUT="$DIR/backoffice-forms-token.yaml"
[ -d "$DIR" ] || { echo "Not a gitops checkout with the backoffice's secrets: $DIR is missing" >&2; exit 1; }
[ ! -e "$OUT" ] || { echo "Refusing to overwrite $OUT" >&2; exit 1; }

# 48 characters of base64url (36 random bytes): above the API's 32-character minimum, and only letters, digits, - and _
# (apps/api/src/config.ts).
TOKEN="$(openssl rand -base64 36 | tr '+/' '-_')"
[[ "$TOKEN" =~ ^[A-Za-z0-9_-]{48}$ ]] || { echo "Couldn't generate the token" >&2; exit 1; }

tmp="$OUT.tmp"
if ! {
  printf '# yamllint disable rule:line-length\n'
  printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
  printf "# token: FORMS_TOKEN, the secret the census form's server sends the API (openssl rand, 48 characters).\n"
  printf '# Generated by scripts/seal-forms-token.sh in pauseai-en-espanol/backoffice.\n'
  kubectl create secret generic backoffice-forms-token -n backoffice \
    --from-file=token=<(printf %s "$TOKEN") --dry-run=client -o yaml \
    | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
    | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
} >"$tmp"; then
  rm -f "$tmp"
  echo "Failed to seal $OUT" >&2
  exit 1
fi
mv "$tmp" "$OUT"
unset TOKEN
echo "sealed $OUT"
cat <<EOF
Done. In clusters/danilupion-com/values/apps/backoffice.yaml, set formsTokenSecret: { name: backoffice-forms-token }
under both backoffice-api: and backoffice-forms: (the API also needs publicDatabaseUrlSecret, from
seal-gitops-secrets.sh). Review with git -C "$GITOPS" diff, then commit.
EOF
