#!/usr/bin/env bash
# Generates the key that seals Global's Airtable view link in the database (AIRTABLE_LINK_KEY, M1, ADR-0005) and seals
# it for the cluster into a gitops checkout (settings: scripts/lib/deploy-settings.sh): one SealedSecret,
# backoffice-airtable-key with the key `AIRTABLE_LINK_KEY`, which the API chart's airtableSync.linkKeySecret names (the
# API and the sync's CronJob both read it). The link itself isn't here: admins paste it in Ajustes, and the API stores it
# encrypted with this key. Nothing secret is printed or written unencrypted: the key lives in a shell variable and
# reaches kubectl through /dev/fd, never argv or a file.
#
# Usage: scripts/seal-airtable-key.sh <path-to-gitops>
# Non-interactive. Refuses to overwrite: a new key can't open the link stored with the old one, so to rotate, delete the
# sealed file, run this again, deploy, and have an admin paste the link again in Ajustes.
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
. "$(dirname "$0")/lib/deploy-settings.sh"
load_deploy_settings "$GITOPS" APP_DIR KUBESEAL_ARGS
NAMESPACE="${NAMESPACE:-pauseai-es-backoffice}"
read -r -a KUBESEAL_ARGS <<<"$KUBESEAL_ARGS"

DIR="$GITOPS/$APP_DIR/secrets"
OUT="$DIR/backoffice-airtable-key.yaml"
[ -d "$DIR" ] || { echo "Not a gitops checkout with the backoffice's secrets: $DIR is missing" >&2; exit 1; }
[ ! -e "$OUT" ] || { echo "Refusing to overwrite $OUT" >&2; exit 1; }

# 32 random bytes in base64, as the API reads it (apps/api/src/imports/airtable-link.ts).
KEY="$(openssl rand -base64 32)"
[[ "$KEY" =~ ^[A-Za-z0-9+/]{43}=$ ]] || { echo "Couldn't generate the key" >&2; exit 1; }

tmp="$OUT.tmp"
if ! {
  printf '# yamllint disable rule:line-length\n'
  printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
  printf "# AIRTABLE_LINK_KEY: seals Global's Airtable view link in the database (openssl rand, 32 bytes; ADR-0005).\n"
  printf '# Generated by scripts/seal-airtable-key.sh in pauseai-en-espanol/backoffice.\n'
  kubectl create secret generic backoffice-airtable-key -n "$NAMESPACE" \
    --from-file=AIRTABLE_LINK_KEY=<(printf %s "$KEY") --dry-run=client -o yaml \
    | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
    | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
} >"$tmp"; then
  rm -f "$tmp"
  unset KEY
  echo "Failed to seal $OUT" >&2
  exit 1
fi
mv "$tmp" "$OUT"
unset KEY
echo "sealed $OUT"
values_file="${VALUES_FILE:-the backoffice values file}"
cat <<EOF
Done. In $values_file, under backoffice-api:, turn airtableSync on with
ingestDatabaseUrlSecret: { name: backoffice-ingest-db } and linkKeySecret: { name: backoffice-airtable-key }
(docs/runbooks/deploying.md). Review with git -C "$GITOPS" diff, then commit. Once deployed, an admin pastes the
view's link in Ajustes and turns the sync on.
EOF
